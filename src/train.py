from __future__ import annotations
from typing import Dict, List

import torch
import torch.nn as nn
import torch.nn.functional as F
from torch_geometric.nn import (
    GCNConv,
    GATConv,
    ChebConv,
    GCN2Conv,
    PairNorm,
)

################################################################################
#  MODEL COMPONENTS
################################################################################

class SpatialBranch(nn.Module):
    """K-max hop GCN with per-node Gumbel-sigmoid gate."""

    def __init__(self, in_dim: int, out_dim: int, K: int = 3, tau: float = 0.6):
        super().__init__()
        self.K = K
        self.tau = tau
        self.convs = nn.ModuleList(
            [GCNConv(in_dim if k == 0 else out_dim, out_dim) for k in range(K)]
        )
        self.gate = nn.Linear(in_dim, K)  # produce logits g_i for hops

    def forward(self, x, edge_index):
        gate_logits = self.gate(x)  # (N,K)
        g = torch.sigmoid(gate_logits / self.tau)  # soft gate  ∈(0,1)
        h = x
        outs = []
        for k, conv in enumerate(self.convs):
            h = F.relu(conv(h, edge_index))
            outs.append(h * g[:, k : k + 1])
        return torch.stack(outs, dim=0).sum(0) if outs else x  # safety for K==0


class SpectralBranch(nn.Module):
    """Chebyshev filter whose coefficients θ_k are generated by a small MLP."""

    def __init__(self, in_dim: int, out_dim: int, K: int = 5):
        super().__init__()
        self.K = K
        self.cheb = ChebConv(in_dim, out_dim, K)
        self.coeff_mlp = nn.Sequential(
            nn.Linear(in_dim * 2, 128), nn.ReLU(), nn.Linear(128, K)
        )

    def forward(self, x, edge_index):
        stats = torch.cat([x.mean(0), x.var(0)], 0)
        theta = self.coeff_mlp(stats).tanh()  # θ_k ∈ (−1,1)
        return F.relu(self.cheb(x, edge_index, theta)) if self.K else x


class DDAFLayer(nn.Module):
    """One dual-domain adaptive filtering layer."""

    def __init__(self, in_dim: int, h: int, K_spatial: int = 3, K_cheb: int = 5):
        super().__init__()
        self.spatial = SpatialBranch(in_dim, h, K_spatial)
        self.spectral = SpectralBranch(in_dim, h, K_cheb)
        self.alpha = nn.Linear(in_dim, 2)  # attention between the two branches
        self.bn = nn.BatchNorm1d(h * 2)

    def forward(self, x, edge_index):
        xs = self.spatial(x, edge_index)
        xf = self.spectral(x, edge_index)
        a = torch.softmax(self.alpha(x), dim=-1)  # (N,2)
        out = torch.cat([xs * a[:, 0:1], xf * a[:, 1:2]], 1)
        return self.bn(out)


class MIHead(nn.Module):
    """Random-feature projector used in InfoNCE estimation."""

    def __init__(self, in_dim: int, proj: int = 128):
        super().__init__()
        self.l = nn.Linear(in_dim, proj)

    def forward(self, x):
        return F.normalize(self.l(x), dim=-1)


def info_nce(z0: torch.Tensor, z1: torch.Tensor) -> torch.Tensor:
    """Lightweight InfoNCE with a single positive per sample."""

    z0, z1 = F.normalize(z0, dim=-1), F.normalize(z1, dim=-1)
    N = z0.size(0)
    pos = (z0 * z1).sum(-1, keepdim=True)  # (N,1)
    sim = z0 @ z1.t()  # (N,N)
    logits = torch.cat([pos, sim], 1)
    labels = torch.zeros(N, dtype=torch.long, device=z0.device)
    return F.cross_entropy(logits, labels)


class DDAFGNN(nn.Module):
    """Full DDAF-GNN network with configurable depth."""

    def __init__(
        self,
        input_dim: int,
        hidden: int,
        out_dim: int,
        layers: int = 16,
        K_sp: int = 3,
        K_ch: int = 5,
        lmbd_mi: float = 0.1,
    ):
        super().__init__()
        self.layers = nn.ModuleList(
            [
                DDAFLayer(
                    input_dim if i == 0 else hidden * 2, hidden, K_sp, K_ch
                )
                for i in range(layers)
            ]
        )
        self.classifier = nn.Linear(hidden * 2, out_dim)
        self.mi_in = MIHead(input_dim)
        self.mi_out = MIHead(hidden * 2)
        self.lmbd = lmbd_mi

    def forward(self, x, edge_index):
        for layer in self.layers:
            x = F.dropout(layer(x, edge_index), p=0.5, training=self.training)
        h = x
        logits = self.classifier(h)
        return logits, h

    # ------------------------------------------------------------------
    #  Loss helper (includes optional MI regulariser)
    # ------------------------------------------------------------------
    def loss(self, logits, h, data, train_mask):
        ce = F.cross_entropy(logits[train_mask], data.y[train_mask])
        if self.lmbd > 0:
            mi = info_nce(self.mi_in(data.x), self.mi_out(h))
            return ce + self.lmbd * mi
        return ce


