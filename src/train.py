class EarlyStopper:
    """Simple validation-loss based early stopping."""

    def __init__(self, patience: int = 100):
        self.patience = patience
        self.best = -1
        self.best_state = None
        self.count = 0

    def step(self, val_acc: float, model: nn.Module):
        if val_acc > self.best:
            self.best = val_acc
            # keep weights on CPU to save GPU RAM
            self.best_state = {k: v.cpu() for k, v in model.state_dict().items()}
            self.count = 0
        else:
            self.count += 1
        return self.count > self.patience


################################################################################
#  VARIANT BUILDER (used in component ablation)
################################################################################

def build_ddaf_variant(cfg: Dict, input_dim: int, out_dim: int) -> DDAFGNN:
    """Create a DDAF model and disable branches according to *cfg*."""

    model = DDAFGNN(
        input_dim,
        64,
        out_dim,
        layers=16,
        lmbd_mi=cfg["lambda_mi"],
        K_sp=cfg["k_spatial"],
        K_ch=cfg["k_cheb"],
    )

    # branch disabling via setting K=0 after construction
    if cfg.get("disable_spatial", False):
        for p in model.modules():
            if isinstance(p, SpatialBranch):
                p.K = 0
                p.convs = nn.ModuleList()  # free memory

    if cfg.get("disable_spectral", False):
        for p in model.modules():
            if isinstance(p, SpectralBranch):
                p.K = 0

    return model
