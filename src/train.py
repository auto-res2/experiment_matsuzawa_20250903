def build_baseline(
    name: str,
    in_dim: int,
    hidden: int,
    out_dim: int,
    layers: int,
) -> nn.Module:
    name = name.lower()

    if name == "gcn":
        convs = nn.ModuleList(
            [GCNConv(in_dim if i == 0 else hidden, hidden) for i in range(layers - 1)]
        )
        lin = nn.Linear(hidden, out_dim)

        class Net(nn.Module):
            def forward(self, x, edge_index):
                for c in convs:
                    x = F.relu(c(x, edge_index))
                    x = F.dropout(x, 0.5, self.training)
                return lin(x)

        return Net()

    if name == "gat":
        heads = 8
        convs = nn.ModuleList(
            [
                GATConv(
                    in_dim if i == 0 else hidden * heads,
                    hidden,
                    heads=heads,
                    dropout=0.6,
                )
                for i in range(layers - 1)
            ]
        )
        lin = nn.Linear(hidden * heads, out_dim)

        class Net(nn.Module):
            def forward(self, x, edge_index):
                for c in convs:
                    x = F.elu(c(x, edge_index))
                return lin(x)

        return Net()

    if name == "gcnii":
        convs = nn.ModuleList(
            [GCN2Conv(hidden, alpha=0.3, theta=1.0, layer=i + 1) for i in range(layers)]
        )
        proj = nn.Linear(in_dim, hidden)
        lin = nn.Linear(hidden, out_dim)

        class Net(nn.Module):
            def forward(self, x, edge_index):
                h0 = F.relu(proj(x))
                h = h0
                for c in convs:
                    h = F.relu(c(h, h0, edge_index))
                    h = F.dropout(h, 0.5, self.training)
                return lin(h)

        return Net()

    if name == "pairnorm-gcn":
        convs = nn.ModuleList(
            [GCNConv(in_dim if i == 0 else hidden, hidden) for i in range(layers - 1)]
        )
        pn = PairNorm("PN")
        lin = nn.Linear(hidden, out_dim)

        class Net(nn.Module):
            def forward(self, x, edge_index):
                for c in convs:
                    x = F.relu(c(x, edge_index))
                    x = pn(x)
                    x = F.dropout(x, 0.5, self.training)
                return lin(x)

        return Net()

    raise ValueError(f"Unknown baseline {name}")


